// captureScenario is one kind of manual change made on a live database.
// The property under test is the reason capture exists: the migration
// it writes, applied by `up` on a database built only from the
// migration files, reproduces the live structure exactly; and its down
// takes that database back to the baseline.
type captureScenario struct {
	name     string
	baseline string
	drift    string
	// manualDown marks a change PostgreSQL cannot undo by DDL (an enum
	// value cannot be removed): down must say so instead of pretending.
	manualDown bool
}

var captureScenarios = []captureScenario{
	{
		name:     "new table with serial key, fk, unique, check, index",
		baseline: `CREATE TABLE users (id serial PRIMARY KEY, name text NOT NULL);`,
		drift: `CREATE TABLE orders (
				id serial PRIMARY KEY,
				user_id integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
				code varchar(20) NOT NULL UNIQUE,
				total numeric(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
				created_at timestamptz NOT NULL DEFAULT now()
			);
			CREATE INDEX orders_user_idx ON orders (user_id, created_at DESC);`,
	},
	{
		name:     "serial and bigserial columns added to an existing table",
		baseline: `CREATE TABLE items (name text NOT NULL);`,
		drift: `ALTER TABLE items ADD COLUMN id serial;
			ALTER TABLE items ADD COLUMN seq bigserial;`,
	},
	{
		name:     "identity and generated columns",
		baseline: `CREATE TABLE users (id serial PRIMARY KEY, name text NOT NULL);`,
		drift: `CREATE TABLE events (
				id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
				ref integer GENERATED BY DEFAULT AS IDENTITY,
				price numeric NOT NULL,
				qty integer NOT NULL,
				amount numeric GENERATED ALWAYS AS (price * qty) STORED
			);`,
	},
	{
		name:     "column altered: type, default, not null",
		baseline: `CREATE TABLE users (id serial PRIMARY KEY, name varchar(50), age integer NOT NULL, role text);`,
		drift: `ALTER TABLE users ALTER COLUMN name TYPE text;
			ALTER TABLE users ALTER COLUMN name SET NOT NULL;
			ALTER TABLE users ALTER COLUMN age DROP NOT NULL;
			ALTER TABLE users ALTER COLUMN role SET DEFAULT 'member';
			ALTER TABLE users ADD COLUMN active boolean NOT NULL DEFAULT true;`,
	},
	{
		name:     "enum created, used, and extended",
		baseline: `CREATE TYPE mood AS ENUM ('sad', 'ok'); CREATE TABLE users (id serial PRIMARY KEY);`,
		drift: `ALTER TYPE mood ADD VALUE 'happy';
			CREATE TYPE status AS ENUM ('new', 'done');
			ALTER TABLE users ADD COLUMN state status NOT NULL DEFAULT 'new';
			ALTER TABLE users ADD COLUMN feeling mood;`,
		manualDown: true,
	},
	{
		name:     "standalone sequence used as a default",
		baseline: `CREATE TABLE tickets (id integer PRIMARY KEY);`,
		drift: `CREATE SEQUENCE ticket_numbers START 1000 INCREMENT 10;
			ALTER TABLE tickets ADD COLUMN number integer NOT NULL DEFAULT nextval('ticket_numbers');`,
	},
	{
		name:     "table in a new schema",
		baseline: `CREATE TABLE users (id serial PRIMARY KEY);`,
		drift: `CREATE SCHEMA billing;
			CREATE TABLE billing.invoices (id serial PRIMARY KEY, user_id integer REFERENCES public.users (id));`,
	},
	{
		name:     "primary key replaced",
		baseline: `CREATE TABLE accounts (id integer CONSTRAINT accounts_pkey PRIMARY KEY, code text NOT NULL);`,
		drift: `ALTER TABLE accounts DROP CONSTRAINT accounts_pkey;
			ALTER TABLE accounts ADD CONSTRAINT accounts_code_pk PRIMARY KEY (code);`,
	},
	{
		name: "constraint and index altered",
		baseline: `CREATE TABLE users (id serial PRIMARY KEY, age integer CONSTRAINT age_ok CHECK (age > 0), email text);
			CREATE INDEX users_email_idx ON users (email);`,
		drift: `ALTER TABLE users DROP CONSTRAINT age_ok;
			ALTER TABLE users ADD CONSTRAINT age_ok CHECK (age > 17);
			DROP INDEX users_email_idx;
			CREATE UNIQUE INDEX users_email_idx ON users (lower(email));`,
	},
	{
		name: "destructive: column and table dropped",
		baseline: `CREATE TABLE users (id serial PRIMARY KEY, nick text, bio text);
			CREATE TABLE legacy (id integer);`,
		drift: `ALTER TABLE users DROP COLUMN bio;
			DROP TABLE legacy;`,
	},
}

func TestCaptureReproducesLiveSchema(t *testing.T) {
	if os.Getenv("DATABASE_URL") == "" {
		t.Skip("DATABASE_URL environment variable not set, skipping capture integration test")
	}
	for i, sc := range captureScenarios {
		t.Run(sc.name, func(t *testing.T) {
			runCaptureScenario(t, i, sc)
		})
	}
}

func runCaptureScenario(t *testing.T, i int, sc captureScenario) {
	ctx := context.Background()
	dir := t.TempDir()
	liveURL := scratchDatabase(t, "migration_e2e_live_"+string(rune('a'+i)))
	freshURL := scratchDatabase(t, "migration_e2e_fresh_"+string(rune('a'+i)))

	writeFile(t, filepath.Join(dir, "001_baseline.up.sql"), sc.baseline)
	writeFile(t, filepath.Join(dir, "001_baseline.down.sql"), "SELECT 1;")
	err := runMigration(ctx, dir, liveURL, "up", false, false)
	if err != nil {
		t.Fatalf("baseline up: %v", err)
	}
	baseline, err := snapshot.Load(dir, 1)
	if err != nil {
		t.Fatalf("baseline snapshot: %v", err)
	}

	live := openTestDB(t, liveURL)
	_, err = live.ExecContext(ctx, sc.drift)
	if err != nil {
		t.Fatalf("drift: %v", err)
	}
	err = cmdCapture(ctx, liveURL, dir, "drift", false)
	if err != nil {
		t.Fatalf("capture: %v", err)
	}
	liveModel, err := introspect.Read(ctx, live)
	if err != nil {
		t.Fatal(err)
	}

	upPath := filepath.Join(dir, "002_drift.up.sql")
	downPath := filepath.Join(dir, "002_drift.down.sql")
	upSQL := readTestFile(t, upPath)
	downSQL := readTestFile(t, downPath)
	t.Logf("up:\n%s\ndown:\n%s", upSQL, downSQL)

	// A reviewer accepts the commented destructive statements before the
	// migration ships; the test does the same.
	writeFile(t, upPath, uncommentDestructive(upSQL))

	_, _, err = core.Run(ctx, dir, freshURL, "up")
	if err != nil {
		t.Fatalf("captured migration does not apply on a fresh database: %v", err)
	}
	fresh := openTestDB(t, freshURL)
	assertSameSchema(t, "fresh database after up", fresh, liveModel)

	// The down file as written must run (destructive lines stay inert)...
	tx, err := fresh.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	_, err = tx.ExecContext(ctx, downSQL)
	_ = tx.Rollback()
	if err != nil {
		t.Fatalf("captured down does not execute as written: %v", err)
	}

	if sc.manualDown {
		if !strings.Contains(downSQL, "-- MANUAL:") {
			t.Errorf("down must flag the irreversible change as MANUAL:\n%s", downSQL)
		}
		return
	}

	// ...and, accepted in full, it restores the baseline.
	writeFile(t, downPath, uncommentDestructive(downSQL))
	_, _, err = core.Run(ctx, dir, freshURL, "down 1")
	if err != nil {
		t.Fatalf("captured down: %v", err)
	}
	assertSameSchema(t, "fresh database after down", fresh, baseline)
}

func uncommentDestructive(sql string) string {
	lines := strings.Split(sql, "\n")
	for i := 1; i < len(lines); i++ {
		if strings.HasPrefix(lines[i-1], "-- DESTRUCTIVE:") {
			lines[i] = strings.TrimPrefix(lines[i], "-- ")
		}
	}
	return strings.Join(lines, "\n")
}

func assertSameSchema(t *testing.T, what string, db *sql.DB, want *introspect.Schema) {
	t.Helper()
	got, err := introspect.Read(context.Background(), db)
	if err != nil {
		t.Fatal(err)
	}
	if reflect.DeepEqual(got, want) {
		return
	}
	changes := diff.Compare(want, got)
	var b strings.Builder
	for _, c := range changes {
		b.WriteString("  " + c.String() + "\n")
	}
	t.Errorf("%s differs from expected schema:\n%s", what, b.String())
}

func openTestDB(t *testing.T, dbURL string) *sql.DB {
	t.Helper()
	db, err := sql.Open("pgx", dbURL)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		_ = db.Close()
	})
	return db
}

func readTestFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path) // #nosec G304 -- test temp dir
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	err := os.WriteFile(path, []byte(content), 0o600)
	if err != nil {
		t.Fatal(err)
	}
}

// Two captures in a row must chain: a database built from all the files
// matches the live one, and reverting both lands on the baseline.
func TestCaptureChain(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	liveURL := scratchDatabase(t, "migration_e2e_chain_live")
	freshURL := scratchDatabase(t, "migration_e2e_chain_fresh")

	writeFile(t, filepath.Join(dir, "001_baseline.up.sql"), `CREATE TABLE users (id serial PRIMARY KEY, name text);`)
	writeFile(t, filepath.Join(dir, "001_baseline.down.sql"), `DROP TABLE users;`)
	err := runMigration(ctx, dir, liveURL, "up", false, false)
	if err != nil {
		t.Fatalf("baseline up: %v", err)
	}
	live := openTestDB(t, liveURL)

	_, err = live.ExecContext(ctx, `CREATE TABLE posts (id bigserial PRIMARY KEY, user_id integer REFERENCES users (id), body text NOT NULL);`)
	if err != nil {
		t.Fatal(err)
	}
	err = cmdCapture(ctx, liveURL, dir, "posts", false)
	if err != nil {
		t.Fatalf("first capture: %v", err)
	}

	_, err = live.ExecContext(ctx, `ALTER TABLE posts ADD COLUMN published boolean NOT NULL DEFAULT false;
		CREATE INDEX posts_published_idx ON posts (published) WHERE published;`)
	if err != nil {
		t.Fatal(err)
	}
	err = cmdCapture(ctx, liveURL, dir, "publish_flag", false)
	if err != nil {
		t.Fatalf("second capture: %v", err)
	}
	liveModel, err := introspect.Read(ctx, live)
	if err != nil {
		t.Fatal(err)
	}

	n, _, err := core.Run(ctx, dir, freshURL, "up")
	if err != nil || n != 3 {
		t.Fatalf("fresh up applied %d (want 3): %v", n, err)
	}
	fresh := openTestDB(t, freshURL)
	assertSameSchema(t, "fresh database after the chain", fresh, liveModel)

	for _, f := range []string{"002_posts.down.sql", "003_publish_flag.down.sql"} {
		path := filepath.Join(dir, f)
		writeFile(t, path, uncommentDestructive(readTestFile(t, path)))
	}
	_, _, err = core.Run(ctx, dir, freshURL, "down 2")
	if err != nil {
		t.Fatalf("down 2: %v", err)
	}
	baseline, err := snapshot.Load(dir, 1)
	if err != nil {
		t.Fatal(err)
	}
	assertSameSchema(t, "fresh database after down 2", fresh, baseline)
}

// A partitioned table is detected and reported, never generated:
// recreating one can take long and lose data.
func TestCapturePartitionedTableIsManual(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	liveURL := scratchDatabase(t, "migration_e2e_partition")

	writeFile(t, filepath.Join(dir, "001_baseline.up.sql"), `CREATE TABLE events (id integer, at date NOT NULL);`)
	writeFile(t, filepath.Join(dir, "001_baseline.down.sql"), `DROP TABLE events;`)
	err := runMigration(ctx, dir, liveURL, "up", false, false)
	if err != nil {
		t.Fatalf("baseline up: %v", err)
	}
	live := openTestDB(t, liveURL)
	_, err = live.ExecContext(ctx, `
		CREATE TABLE logs (id integer, at date NOT NULL) PARTITION BY RANGE (at);
		CREATE TABLE logs_2026 PARTITION OF logs FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
		ALTER TABLE events RENAME TO events_old;
		CREATE TABLE events (id integer, at date NOT NULL) PARTITION BY RANGE (at);`)
	if err != nil {
		t.Fatal(err)
	}

	err = cmdCapture(ctx, liveURL, dir, "partitions", false)
	if err != nil {
		t.Fatalf("capture: %v", err)
	}
	up := readTestFile(t, filepath.Join(dir, "002_partitions.up.sql"))
	for _, want := range []string{
		"-- MANUAL: public.logs is partitioned",
		"-- MANUAL: public.events is partitioned",
		"--   old: not partitioned",
	} {
		if !strings.Contains(up, want) {
			t.Errorf("up missing %q:\n%s", want, up)
		}
	}
	if strings.Contains(up, "CREATE TABLE public.logs") || strings.Contains(up, "logs_2026") {
		t.Errorf("partitioned table or partition generated as DDL:\n%s", up)
	}
}

// Objects outside the model are reported by name in the captured
// migration so the user writes them by hand; none becomes DDL.
func TestCaptureManualObjects(t *testing.T) {
	ctx := context.Background()
	dir := t.TempDir()
	liveURL := scratchDatabase(t, "migration_e2e_manual")

	writeFile(t, filepath.Join(dir, "001_baseline.up.sql"), `CREATE TABLE users (id serial PRIMARY KEY, name text);
		CREATE VIEW v_old AS SELECT 1 AS x;`)
	writeFile(t, filepath.Join(dir, "001_baseline.down.sql"), `DROP VIEW v_old; DROP TABLE users;`)
	err := runMigration(ctx, dir, liveURL, "up", false, false)
	if err != nil {
		t.Fatalf("baseline up: %v", err)
	}
	live := openTestDB(t, liveURL)
	_, err = live.ExecContext(ctx, `
		DROP VIEW v_old;
		CREATE VIEW v_users AS SELECT id FROM users;
		CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN RETURN NEW; END';
		CREATE TRIGGER audit BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION touch();
		CREATE EXTENSION pgcrypto;`)
	if err != nil {
		t.Fatal(err)
	}

	err = cmdDiff(ctx, liveURL, dir, false)
	if err == nil {
		t.Fatal("diff must report manual objects as drift")
	}
	err = cmdCapture(ctx, liveURL, dir, "manual", false)
	if err != nil {
		t.Fatalf("capture: %v", err)
	}
	up := readTestFile(t, filepath.Join(dir, "002_manual.up.sql"))
	want := "-- MANUAL: drop view public.v_old (not managed by migration; write its DDL here).\n" +
		"-- MANUAL: create extension public.pgcrypto (not managed by migration; write its DDL here).\n" +
		"-- MANUAL: create function public.touch() (not managed by migration; write its DDL here).\n" +
		"-- MANUAL: create trigger public.users.audit (not managed by migration; write its DDL here).\n" +
		"-- MANUAL: create view public.v_users (not managed by migration; write its DDL here).\n"
	if up != want {
		t.Errorf("up:\n%s\nwant:\n%s", up, want)
	}
}
